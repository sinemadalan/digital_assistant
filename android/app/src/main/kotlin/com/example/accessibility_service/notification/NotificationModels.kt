package com.example.accessibility_service.notification

/**
 * High-level notification model representing an event or alert to present to the user.
 */
data class AppNotification(
    val id: Int,
    val type: NotificationType,
    val title: String,
    val message: String,
    val payload: Map<String, String> = emptyMap(),
    val timestampMs: Long = System.currentTimeMillis(),
    val onlyAlertOnce: Boolean = false,
)

/**
 * Supported notification categories/channels.
 * Designed to easily support Phase 2 (push notifications, system alerts, etc.).
 */
enum class NotificationType(
    val channelId: String,
    val channelNameResId: Int? = null,
    val importance: NotificationImportance = NotificationImportance.DEFAULT,
) {
    /**
     * Phase 1: Alerts generated by backend content classification / detections.
     */
    CLASSIFICATION_ALERT(
        channelId = "classification_alerts_v1",
        importance = NotificationImportance.DEFAULT,
    ),

    SERVER_ALERT(
        channelId = "server_alerts_channel",
        importance = NotificationImportance.HIGH,
    ),

    /**
     * Phase 2: General / push notifications.
     */
    PUSH_NOTIFICATION(
        channelId = "push_notifications_channel",
        importance = NotificationImportance.DEFAULT,
    ),

    /**
     * System status or operational notifications (e.g. service state).
     */
    SYSTEM_STATUS(
        channelId = "system_status_channel",
        importance = NotificationImportance.LOW,
    ),
}

enum class NotificationImportance {
    LOW,
    DEFAULT,
    HIGH,
}
